/**
 * The sheet a person reads to confirm or reject each judged-bad label (issue
 * #268). The judge's scores are noisy, so a row counts as a known-bad answer
 * only once a person has set its label in labels.json.
 */
import { validateAnswerQuotes, validateAnswerUrls } from '../../src/processors/verifier/answer-validation.js';
import { VERIFIER_MARKER, type BenchmarkItem } from './fixture.js';

const DEFECT_WORDS = /\b(?:however|but|hallucinat\w*|fabricat\w*|unsupported|not supported|inaccura\w*|incorrect\w*|wrong\w*|misses|missed|omits|omitted|does not|doesn't|did not|not in the evidence|contradict\w*|error|never|fails?|lacks?|overstat\w*|misattribut\w*|mischaracteri\w*)\b/i;
const STOP_WORDS = new Set(['that', 'this', 'with', 'from', 'which', 'agent', 'answer', 'evidence', 'section', 'policy', 'correctly', 'reference', 'however', 'does', 'were', 'have', 'their', 'while', 'also', 'there', 'about', 'under', 'specific', 'score', 'hallucination', 'medicaid']);

const sentences = (text: string) => text.split(/\n+|(?<=[.!?])\s+(?=[A-Z[*"'(])/).map(part => part.trim()).filter(Boolean);
const tokens = (text: string) => new Set((text.toLowerCase().match(/[a-z]{4,}|\d[\d.,/-]*\d|\d/g) ?? []).filter(token => !STOP_WORDS.has(token)));
const clip = (text: string, max: number) => (text.length > max ? `${text.slice(0, max).trimEnd()} …` : text);
const oneLine = (text: string) => text.replace(/\s+/g, ' ').trim();

function bestMatch(candidates: string[], reference: string): string | null {
  const wanted = tokens(reference);
  let best: { text: string; score: number } | null = null;
  for (const candidate of candidates) {
    const found = tokens(candidate);
    let score = 0;
    for (const token of wanted) if (found.has(token)) score += /\d/.test(token) ? 2 : 1;
    if (score > 0 && (!best || score > best.score)) best = { text: candidate, score };
  }
  return best?.text ?? null;
}

/** The judge sentences that state a defect, or the whole explanation when none does. */
export function statedDefect(explanation: string): string {
  const parts = sentences(explanation).filter(sentence => DEFECT_WORDS.test(sentence));
  return oneLine(parts.length ? parts.join(' ') : explanation);
}

export interface ReviewRow {
  id: string;
  defect: string;
  /** The answer sentence sharing the most words with the stated defect. */
  answerSentence: string | null;
  /** The evidence line sharing the most words with that sentence. */
  evidenceExcerpt: { key: string; text: string } | null;
  /** What today's deterministic checks say about the stored answer. */
  checks: string[];
}

export function reviewRow(item: BenchmarkItem): ReviewRow {
  const defect = statedDefect(item.judge.explanation);
  const answerSentence = bestMatch(sentences(item.answer).filter(sentence => sentence.length >= 20), defect);
  // Section text when the turn read any; listings and amendment trails otherwise.
  const bodies = item.sources.filter(source => source.toolName === 'getSection' || source.toolName === 'resolveAnswerFrame:section');
  const corpus = bodies.length ? bodies : item.sources.filter(source => source.toolName !== 'resolveAnswerFrame');
  // Skip the serialized header (ID, Title, Section, …) of a section entry.
  const body = (text: string) => (text.includes('\nContent:\n') ? text.slice(text.indexOf('\nContent:\n') + 10) : text);
  const lines = corpus.flatMap(source => body(source.text).split('\n').filter(line => line.trim().length >= 40).map(line => ({ key: source.key, text: line.trim() })));
  const evidenceLine = answerSentence ? bestMatch(lines.map(line => line.text), answerSentence) : null;
  const checks: string[] = [];
  const { unknownUrls } = validateAnswerUrls(item.answer, item.sources);
  if (unknownUrls.length) checks.push(`link not in the stored evidence: ${[...new Set(unknownUrls)].join(', ')}`);
  const { unknownQuotes } = validateAnswerQuotes(item.answer, item.sources);
  if (unknownQuotes.length) checks.push(`${unknownQuotes.length} quotation(s) not in the stored evidence`);
  if (VERIFIER_MARKER.test(item.answer)) checks.push('the stored answer carries a verifier marker');
  return {
    id: item.id, defect, answerSentence,
    evidenceExcerpt: evidenceLine ? { key: lines.find(line => line.text === evidenceLine)!.key, text: evidenceLine } : null,
    checks,
  };
}

/** Items in sheet order: by question, then by stored run. labels.json uses the same order. */
export function sheetOrder(items: BenchmarkItem[]): BenchmarkItem[] {
  return [...items].sort((a, b) => a.questionId.localeCompare(b.questionId) || a.id.localeCompare(b.id));
}

export function renderReviewSheet(items: BenchmarkItem[]): string {
  const questions = new Set(items.map(item => item.questionId));
  const out = [
    '# Judged-bad answers: review sheet',
    '',
    `Generated by \`scripts/verifier-benchmark/build-fixture.ts\`; do not edit by hand. ${items.length} stored answers over ${questions.size} questions,`,
    'in the same order as `labels.json`.',
    '',
    'For each row decide whether the answer states something its stored evidence does not support, then set its',
    '`label` in `labels.json` to `confirmed-bad` or `not-bad` (and add a `note` if useful). Every row starts',
    '`unconfirmed`. The judge is noisy: a complaint about a link is wrong when "Automated checks" does not list that',
    'link as missing from the evidence. The answer sentence and the evidence excerpt are chosen by word overlap with',
    'the judge\'s text, so they are a starting point and can be the wrong passage; the full answer and evidence are in',
    '`judged-bad.json`.',
    '',
  ];
  let question = '';
  for (const item of sheetOrder(items)) {
    if (item.questionId !== question) {
      question = item.questionId;
      out.push(`## ${question}`, '', `**Question:** ${oneLine(item.question)}`, '');
    }
    const row = reviewRow(item);
    const { judge, stored } = item;
    out.push(
      `### ${item.id}`,
      '',
      `- **Judge scores (0 to 3):** factual accuracy ${judge.factual_accuracy}, hallucination ${judge.hallucination}, overall ${judge.overall}. Stored run: verifier ${stored.verifierModel ?? 'unknown'}, outcome ${stored.verifierOutcome}, commit ${stored.gitSha ?? 'unknown'}.`,
      `- **Automated checks:** ${row.checks.length ? row.checks.join('; ') : 'every link and long quotation in the answer is in the stored evidence; no marker'}`,
      `- **Judge's stated defect:** ${clip(row.defect, 900)}`,
      `- **Answer sentence (closest match):** ${row.answerSentence ? clip(oneLine(row.answerSentence), 600) : 'none found'}`,
      `- **Evidence excerpt (closest match${row.evidenceExcerpt ? `, \`${row.evidenceExcerpt.key}\`` : ''}):** ${row.evidenceExcerpt ? clip(oneLine(row.evidenceExcerpt.text), 600) : 'none found'}`,
      '',
    );
  }
  return out.join('\n');
}
