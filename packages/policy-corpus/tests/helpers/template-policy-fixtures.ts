// Section lists copied from parsed NC clinical coverage policies (the loader's
// section builder over the parsed sidecars in packages/pipeline/data/parsed/
// clinical-policies, June 2026 parse). Numbers, titles and empty bodies are the
// real ones; a non-empty body is cut to an excerpt and `chars` keeps the real
// length. `parents` holds the loader's parent links as the serving graph has
// them, so an unnumbered heading (for example "a. 42 U.S.C. § 1396d(r)") has no
// parent and an empty section it belongs under stays empty.
//
// Generated once; edit by hand only to add a section from the same source.

import {
  containerBodyRecords,
  documentGraphHandlers,
  normalizeQueryText,
  outlineRecord,
  type GraphDocument,
  type SessionHandler,
} from './graph-fixtures.js';

export interface TemplatePolicy {
  /** Parsed sidecar the sections were copied from. */
  source: string;
  document: GraphDocument;
  /** Section id to parent section id, for sections the loader linked. */
  parents: Record<string, string>;
}

/**
 * Hydration handlers for a template policy: everything documentGraphHandlers
 * gives, plus the two queries getSection runs for a heading with no text of
 * its own (the document outline with the stored parent links, then the body
 * slices), so an empty container reads as it does on the graph.
 */
export function templatePolicyHandlers(policy: TemplatePolicy): SessionHandler[] {
  const { document, parents } = policy;
  const ids = new Set(document.sections.map((section) => section.id));
  const bodies = Object.fromEntries(document.sections.map((section) => [section.id, section.content]));
  return [
    ...documentGraphHandlers(document),
    {
      label: `sectionOutline(${document.id})`,
      optional: true,
      match: (query, params) =>
        normalizeQueryText(query).includes('MATCH (d:Document)-[:HAS_SECTION]->(:Section {id: $id}) MATCH (d)-[:HAS_SECTION]->(other:Section)') &&
        ids.has(String(params.id)),
      result: {
        records: document.sections.map((section) =>
          outlineRecord({
            id: section.id,
            title: section.title,
            sectionNumber: section.number,
            chars: Array.from(section.content).length,
            parentId: parents[section.id] ?? null,
          }),
        ),
      },
    },
    {
      label: `sectionBodies(${document.id})`,
      optional: true,
      match: (query, params) =>
        query.includes('UNWIND $pieces AS piece') &&
        (params.pieces as Array<{ id: string }>).every((piece) => ids.has(piece.id)),
      respond: (params) => ({
        records: containerBodyRecords(bodies, params.pieces as Array<{ id: string; start: number; length: number }>),
      }),
    },
  ];
}

export function templateSection(policy: TemplatePolicy, number: string) {
  const section = policy.document.sections.find((candidate) => candidate.number === number);
  if (!section) throw new Error(`templateSection: ${policy.document.policyNumber} has no section ${number}`);
  return section;
}

export function templateSectionByTitle(policy: TemplatePolicy, titleStart: string) {
  const section = policy.document.sections.find((candidate) => candidate.title?.startsWith(titleStart));
  if (!section) throw new Error(`templateSectionByTitle: ${policy.document.policyNumber} has no section titled ${titleStart}`);
  return section;
}

